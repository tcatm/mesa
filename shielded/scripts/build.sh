#!/usr/bin/env bash
# Compile the withdraw circuit, run a DEVELOPMENT trusted setup, and export
# the Solidity verifier into contracts/src.
#
# The setup here is single-party and its toxic waste is thrown away on this
# machine, which is fine for tests and a testnet and NOT fine for mainnet
# funds: whoever ran it could forge proofs if they kept the randomness.
# Mainnet needs a multi-party phase-2 ceremony on top of a public phase-1
# file (e.g. the Hermez/Polygon powers of tau). See docs/shielded.md.
set -euo pipefail
cd "$(dirname "$0")/.."

POT=14            # 2^14 constraints; the circuit needs ~6k
OUT=build
mkdir -p "$OUT"
snarkjs="node_modules/.bin/snarkjs"

circom circuits/withdraw.circom --r1cs --wasm --sym -o "$OUT" >/dev/null
"$snarkjs" r1cs info "$OUT/withdraw.r1cs" | grep -E "Constraints|Public|Private"

if [ ! -f "$OUT/pot${POT}_final.ptau" ]; then
  "$snarkjs" powersoftau new bn128 "$POT" "$OUT/pot${POT}_0.ptau" >/dev/null
  "$snarkjs" powersoftau contribute "$OUT/pot${POT}_0.ptau" "$OUT/pot${POT}_1.ptau" \
    --name="mesa dev" -e="$(head -c 64 /dev/urandom | base64)" >/dev/null
  "$snarkjs" powersoftau prepare phase2 "$OUT/pot${POT}_1.ptau" "$OUT/pot${POT}_final.ptau" >/dev/null
  rm -f "$OUT/pot${POT}_0.ptau" "$OUT/pot${POT}_1.ptau"
fi

"$snarkjs" groth16 setup "$OUT/withdraw.r1cs" "$OUT/pot${POT}_final.ptau" "$OUT/withdraw_0.zkey" >/dev/null
"$snarkjs" zkey contribute "$OUT/withdraw_0.zkey" "$OUT/withdraw.zkey" \
  --name="mesa dev" -e="$(head -c 64 /dev/urandom | base64)" >/dev/null
rm -f "$OUT/withdraw_0.zkey"
"$snarkjs" zkey export verificationkey "$OUT/withdraw.zkey" "$OUT/withdraw.vkey.json"

V=../contracts/src/WithdrawVerifier.sol
"$snarkjs" zkey export solidityverifier "$OUT/withdraw.zkey" "$V"
# One name per contract in the repo, and the compiler version the repo pins.
sed -i -e 's/contract Groth16Verifier/contract WithdrawVerifier/' \
       -e 's/pragma solidity >=0.7.0 <0.9.0;/pragma solidity 0.8.26;/' "$V"
sed -i '1s/^/\/\/ Generated by shielded\/scripts\/build.sh from circuits\/withdraw.circom. Do not edit.\n/' "$V"
echo "verifier -> $V"
